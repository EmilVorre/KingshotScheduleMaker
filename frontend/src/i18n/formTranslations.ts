export function tForm(lang: FormLang, key: string, params?: Record<string, string | number>): string {
  let s = translations[lang]?.[key] ?? translations.en[key] ?? key
  if (params) {
    s = s.replace(/{(\w+)}/g, (_, k) => String(params[k] ?? `{${k}}`))
  }
  return s
}
